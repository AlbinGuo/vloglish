def looks_like_isp(value: str | None) -> bool:
    if not value:
        return False
    text = value.strip()
    if not text or text == "0":
        return False
    if text in _ISP_EXACT:
        return True
    lowered = text.lower()
    if any(k in lowered for k in ("telecom", "vodafone", "amazon", "at&t", " inc", " ltd", " llc")):
        return True
    if any(k in text for k in ("电信", "移动", "联通", "铁通", "教育网", "广电")):
        return True
    return False


def normalize_province(raw: str | None) -> str | None:
    if not raw:
        return None
    text = raw.strip()
    if not text or text == "0":
        return None
    if text in _PROVINCE_ALIASES:
        return _PROVINCE_ALIASES[text]
    if text in CHINA_PROVINCES:
        return text
    for suffix in (
        "特别行政区",
        "维吾尔自治区",
        "壮族自治区",
        "回族自治区",
        "自治区",
        "省",
        "市",
    ):
        if text.endswith(suffix) and len(text) > len(suffix):
            base = text[: -len(suffix)]
            if base in CHINA_PROVINCES:
                return base
            if base in _PROVINCE_ALIASES:
                return _PROVINCE_ALIASES[base]
    return None


def province_from_city(raw: str | None) -> str | None:
    if not raw:
        return None
    text = raw.strip()
    if not text or text == "0" or looks_like_isp(text):
        return None
    if text in _CITY_TO_PROVINCE:
        return _CITY_TO_PROVINCE[text]
    if text.endswith("市") and text[:-1] in _CITY_TO_PROVINCE:
        return _CITY_TO_PROVINCE[text[:-1]]
    return None


def resolve_china_province_city(
    country: str | None,
    region: str | None,
    city: str | None,
) -> tuple[str | None, str | None]:
    """从可能错位的历史字段解析出 (省短名, 市名)。"""
    province = normalize_province(region) or normalize_province(country)
    city_name: str | None = None

    if province:
        if city and not looks_like_isp(city) and normalize_province(city) != province:
            city_name = city.strip()
        elif region and not normalize_province(region) and province_from_city(region):
            # region 实际是市，但也能 normalize 成直辖市省名的情况已在上面
            city_name = region.strip()
        return province, city_name

    # 历史错位：region=西安市, city=移动
    province = province_from_city(region) or province_from_city(city)
    if province:
        if region and not looks_like_isp(region) and not normalize_province(region):
            city_name = region.strip()
        elif city and not looks_like_isp(city):
            city_name = city.strip()
        return province, city_name

    return None, None


def is_china_location(country: str | None, region: str | None, city: str | None = None) -> bool:
    c = (country or "").strip()
    r = (region or "").strip()
    if c in CHINA_COUNTRY_NAMES or c in _CHINA_AS_COUNTRY:
        return True
    if normalize_province(c) or normalize_province(r):
        return True
    if province_from_city(r) or province_from_city(city):
        return True
    return False


def normalize_country(raw: str | None) -> tuple[str, str] | None:
    if not raw:
        return None
    text = raw.strip()
    if not text or text == "0":
        return None
    if text in _COUNTRY_TO_WORLD_MAP:
        return _COUNTRY_TO_WORLD_MAP[text]
    return (text, text)


def country_for_stats(country: str | None, region: str | None, city: str | None = None) -> tuple[str, str] | None:
    if is_china_location(country, region, city):
        return ("中国", "China")
    return normalize_country(country)
